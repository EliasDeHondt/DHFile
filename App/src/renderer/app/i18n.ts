const BUNDLES: Record<Language, Record<TextKey, string>> = { en, nl };

export const language = signal<Language>('en');

export function t(key: TextKey, params?: Record<string, string | number>): string {
  const text = BUNDLES[language()][key] ?? en[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : text;
}

@Pipe({ name: 't', pure: false })
export class TPipe implements PipeTransform {
  transform(key: TextKey | string, params?: Record<string, string | number>): string { return t(key as TextKey, params); }
}
